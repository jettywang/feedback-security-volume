"""Small helpers to synthesize LVM2 Physical Volume images in-memory.

Real LVM2 images require privileged tools to produce, which makes it hard to test metadata reconciliation
scenarios (different generations, corrupted newer copies, missing PVs and reordered input). These helpers write
just enough of the on-disk LVM2 structures - label, PV header, descriptors and a metadata area - for
:class:`dissect.volume.lvm.LVM2` to parse them, while keeping full control over the embedded metadata text.
"""

from __future__ import annotations

import io
from dataclasses import dataclass

from dissect.volume.lvm.c_lvm2 import SECTOR_SIZE, c_lvm, lvm_crc32

LABEL_SECTOR = 1
LABEL_OFFSET = SECTOR_SIZE
MDA_OFFSET = 4096
MDA_SIZE = 1044480
DATA_OFFSET = 1048576
DISK_SIZE = 4 * 1024 * 1024
PE_START = 2048
EXTENT_SIZE = 8192
PV_PE_COUNT = 2

LVM2_MAGIC = b" LVM2 x[5A%r0N*>"
LABEL_TYPE = b"LVM2 001"


def _display_uuid(pv_uuid: str) -> str:
    """Render a dash-less on-disk PV UUID in the dash-separated form used inside text metadata."""
    if "-" in pv_uuid:
        return pv_uuid
    return "-".join(pv_uuid[i : i + 4] for i in range(0, len(pv_uuid), 4))


def build_metadata(
    vg_name: str,
    vg_id: str,
    seqno: int,
    pvs: list[tuple[str, str]],
    lvs: dict[str, str] | None = None,
) -> str:
    """Render a minimal but valid LVM2 text metadata configuration.

    Args:
        vg_name: Name of the Volume Group.
        vg_id: Dash-separated Volume Group UUID.
        seqno: Metadata generation counter.
        pvs: ``(pv_name, pv_uuid)`` pairs describing the Physical Volumes, in order.
        lvs: Mapping of logical volume name to the physical volume name its single stripe lives on. When omitted
            a default ``lv0`` striped over the first PV is created.
    """
    lv_specs = lvs or {"lv0": pvs[0][0]}

    pv_blocks = []
    for pv_name, pv_uuid in pvs:
        pv_blocks.append(
            f"""
{pv_name} {{
id = "{_display_uuid(pv_uuid)}"
device = "/dev/{pv_name}"

status = ["ALLOCATABLE"]
flags = []
dev_size = {PV_PE_COUNT * EXTENT_SIZE}
pe_start = {PE_START}
pe_count = {PV_PE_COUNT}
}}"""
        )

    lv_blocks = []
    for lv_name, pv_name in lv_specs.items():
        lv_blocks.append(
            f"""
{lv_name} {{
id = "{lv_name}-uuid-0000-0000-0000-000000000000"
status = ["READ", "WRITE", "VISIBLE"]
flags = []
creation_time = 1516102889
creation_host = "localhost"
segment_count = 1

segment1 {{
start_extent = 0
extent_count = 1

type = "striped"
stripe_count = 1

stripes = [
"{pv_name}", 0
]
}}
}}"""
        )

    return f"""{vg_name} {{
id = "{vg_id}"
seqno = {seqno}
format = "lvm2"
status = ["RESIZEABLE", "READ", "WRITE"]
flags = []
extent_size = {EXTENT_SIZE}
max_lv = 0
max_pv = 0
metadata_copies = 0

physical_volumes {{
{''.join(pv_blocks)}
}}

logical_volumes {{
{''.join(lv_blocks)}
}}

}}
# Generated by a synthetic test image

contents = "Text Format Volume Group"
version = 1

description = ""

creation_host = "localhost"
creation_time = 1516102889
"""


@dataclass
class RawLocationOverride:
    """Instructions to manipulate a raw metadata location in a synthetic image."""

    text: str | None = None
    corrupt_checksum: bool = False
    ignored: bool = False
    corrupt_text: bool = False


@dataclass
class SyntheticPV:
    """A fully assembled synthetic Physical Volume image."""

    pv_uuid: str
    data: bytes

    def open(self) -> io.BytesIO:
        return io.BytesIO(self.data)


def _label_header() -> c_lvm.label_header:
    header = c_lvm.label_header()
    header.id = b"LABELONE"
    header.sector = LABEL_SECTOR
    # Offset from the start of the label sector to the PV header that follows the label header.
    header.offset = len(c_lvm.label_header)
    header.type = LABEL_TYPE
    raw = header.dumps()
    # The checksum covers the whole label header with the checksum field zeroed.
    header.crc = lvm_crc32(raw[:16] + b"\x00\x00\x00\x00" + raw[20:])
    return header


def build_pv(pv_uuid: str, metadata_texts: list[RawLocationOverride | str] | None = None) -> SyntheticPV:
    """Build a Physical Volume image containing one or more raw metadata locations.

    Args:
        pv_uuid: The 32-character dash-less PV UUID.
        metadata_texts: Raw locations to place in the (single) metadata area. Plain strings are wrapped into a
            default :class:`RawLocationOverride`. When ``None`` an empty metadata area is produced.
    """
    overrides: list[RawLocationOverride] = []
    for item in metadata_texts or []:
        overrides.append(item if isinstance(item, RawLocationOverride) else RawLocationOverride(text=item))

    buf = bytearray(DISK_SIZE)

    label = _label_header()
    pv_header = c_lvm.pv_header(pv_uuid=pv_uuid.encode(), device_size=DISK_SIZE)
    data_locn = c_lvm.disk_locn(offset=DATA_OFFSET, size=DISK_SIZE - DATA_OFFSET)
    zero_locn = c_lvm.disk_locn()
    mda_locn = c_lvm.disk_locn(offset=MDA_OFFSET, size=MDA_SIZE)

    cursor = LABEL_OFFSET
    for struct in (label, pv_header, data_locn, zero_locn, mda_locn, zero_locn):
        raw = struct.dumps()
        buf[cursor : cursor + len(raw)] = raw
        cursor += len(raw)

    mda_header = c_lvm.mda_header()
    mda_header.magic = LVM2_MAGIC
    mda_header.version = 1
    mda_header.start = MDA_OFFSET
    mda_header.size = MDA_SIZE

    raw_locations = []
    # Raw location offsets are relative to the metadata area start; leave room for the header and descriptors
    # and align the first text block on a sector boundary like real LVM2 does.
    text_cursor = MDA_OFFSET + 2048
    for override in overrides:
        text = (override.text or "").encode()
        if override.corrupt_text:
            text = b"this is not valid lvm metadata {{{ broken"
        locn = c_lvm.raw_locn()
        locn.offset = text_cursor - MDA_OFFSET
        locn.size = len(text) + 1  # LVM stores a trailing NUL terminator
        locn.flags = c_lvm.RAW_LOCN_IGNORED if override.ignored else 0
        checksum_buffer = text + b"\x00"
        locn.checksum = lvm_crc32(checksum_buffer)
        if override.corrupt_checksum:
            locn.checksum ^= 0xFFFFFFFF
        raw_locations.append(locn)

        buf[text_cursor : text_cursor + len(checksum_buffer)] = checksum_buffer
        text_cursor += locn.size

    terminator = c_lvm.raw_locn()
    mda_bytes = bytearray(mda_header.dumps())
    for locn in [*raw_locations, terminator]:
        mda_bytes += locn.dumps()

    mda_header.checksum = lvm_crc32(b"\x00\x00\x00\x00" + bytes(mda_bytes[4:]))
    mda_bytes[:4] = mda_header.dumps()[:4]
    buf[MDA_OFFSET : MDA_OFFSET + len(mda_bytes)] = mda_bytes

    return SyntheticPV(pv_uuid=pv_uuid, data=bytes(buf))
